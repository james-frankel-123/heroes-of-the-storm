"""
Leak-free win-probability models for the paper-1 revision (Table I, the
feature-set design, greedy-search value functions, the augmented model).

Protocol (identical optimizer to retrain_frozen_stats.train_wp_model: AdamW
lr 5e-4, wd 5e-3, cosine T_max 100, batch 4096, dropout 0.3, <=200 epochs,
patience 25), with two changes from the submission:
  * early stopping and seed selection use the VALIDATION split (core.is_val),
    never the test set;
  * training-row features use out-of-fold statistics (core: oof{k}); val,
    test and post-snapshot rows use the deploy statistics (train games only).
Every spec is trained with 3 seeds (42, 123, 777). The "selected" checkpoint
is the seed with the lowest validation loss; tables report the 3-seed mean.

Metrics per seed, on the paper test set (38,981) and on post-snapshot
no-drift games (NODRIFT, 291,837; overfit2026.gold):
  acc      accuracy over both team orders (the submission's Table I convention)
  ll, acc_sym, slope   log-loss / accuracy / calibration slope of the
           team-order-symmetrized prediction (slope = logistic regression of
           the outcome on logit(p); 1.0 = calibrated, <1 = overconfident)

Usage: python3 paper1_revision/train_wp.py <spec>[,<spec>...] [--gpu 0]
       python3 paper1_revision/train_wp.py --list
"""
